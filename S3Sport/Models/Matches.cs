using System.ComponentModel.DataAnnotations;

namespace S3Sport.Models;

public class Match : BaseEntity, ISoftDelete
{
    public int SportId { get; set; }
    public Sport Sport { get; set; } = null!;

    /// <summary>Null for friendly matches.</summary>
    public int? CompetitionSeasonId { get; set; }
    public CompetitionSeason? CompetitionSeason { get; set; }
    public int? StageId { get; set; }
    public CompetitionStage? Stage { get; set; }
    public int? GroupId { get; set; }
    public CompetitionGroup? Group { get; set; }
    public int? RoundNumber { get; set; }
    [StringLength(100)] public string? RoundName { get; set; }
    /// <summary>For two-legged ties: 1 or 2.</summary>
    public int? LegNumber { get; set; }

    public int HomeTeamId { get; set; }
    public Team HomeTeam { get; set; } = null!;
    public int AwayTeamId { get; set; }
    public Team AwayTeam { get; set; } = null!;

    public int? VenueId { get; set; }
    public Venue? Venue { get; set; }

    /// <summary>Scheduled kick-off in UTC (displayed in Asia/Muscat).</summary>
    public DateTime KickoffAt { get; set; }

    public MatchStatus Status { get; set; }
    public int HomeScore { get; set; }
    public int AwayScore { get; set; }
    public int? HomePenaltyScore { get; set; }
    public int? AwayPenaltyScore { get; set; }
    /// <summary>Set for knockout matches (including penalties). Null = draw/undecided.</summary>
    public int? WinnerTeamId { get; set; }
    public Team? WinnerTeam { get; set; }

    /// <summary>0 = not started, 1 = first half, 2 = second half, 3+ = extra time.</summary>
    public int CurrentPeriod { get; set; }
    public DateTime? StartedAt { get; set; }
    public DateTime? CurrentPeriodStartedAt { get; set; }
    public DateTime? FinishedAt { get; set; }

    /// <summary>The user assigned to record live events for this match.</summary>
    public string? OperatorUserId { get; set; }
    public ApplicationUser? OperatorUser { get; set; }

    /// <summary>Team whose managers created this friendly; they schedule it and record it live.</summary>
    public int? OrganizerTeamId { get; set; }
    public Team? OrganizerTeam { get; set; }

    /// <summary>
    /// Free-text tournament name typed by the organizing team for a match outside the platform's competitions
    /// (null = friendly). Display only: no standings, no competition page.
    /// </summary>
    [StringLength(150)] public string? TournamentName { get; set; }

    [StringLength(500)] public string? Notes { get; set; }

    public bool IsDeleted { get; set; }
    public DateTime? DeletedAt { get; set; }
    [Timestamp] public byte[] RowVersion { get; set; } = null!;

    public ICollection<MatchEvent> Events { get; set; } = new List<MatchEvent>();
    public ICollection<MatchLineup> Lineups { get; set; } = new List<MatchLineup>();
    public ICollection<MatchOfficial> Officials { get; set; } = new List<MatchOfficial>();
    public MatchReport? Report { get; set; }
}

public class MatchEvent : BaseEntity
{
    public int MatchId { get; set; }
    public Match Match { get; set; } = null!;

    public MatchEventType EventType { get; set; }
    public int? TeamId { get; set; }
    public Team? Team { get; set; }
    /// <summary>Scorer / carded player / player coming off.</summary>
    public int? PlayerId { get; set; }
    public Player? Player { get; set; }
    /// <summary>Assist provider / player coming on.</summary>
    public int? RelatedPlayerId { get; set; }
    public Player? RelatedPlayer { get; set; }
    /// <summary>Typed names for a guest team, which has no registered players (instead of PlayerId / RelatedPlayerId).</summary>
    [StringLength(100)] public string? PlayerNameText { get; set; }
    [StringLength(100)] public string? RelatedPlayerNameText { get; set; }

    public int Minute { get; set; }
    public int? ExtraMinute { get; set; }
    public int Period { get; set; }
    [StringLength(300)] public string? Notes { get; set; }

    /// <summary>Generated by the operator screen per click; unique per match to block duplicate submits.</summary>
    public Guid ClientRequestId { get; set; }

    /// <summary>Corrections void events instead of deleting them; the score is recomputed from non-cancelled events.</summary>
    public bool IsCancelled { get; set; }

    public string? CreatedByUserId { get; set; }
    public ApplicationUser? CreatedByUser { get; set; }

    [Timestamp] public byte[] RowVersion { get; set; } = null!;

    public ICollection<MatchEventRevision> Revisions { get; set; } = new List<MatchEventRevision>();
}

/// <summary>History of corrections made to a match event.</summary>
public class MatchEventRevision : BaseEntity
{
    public int MatchEventId { get; set; }
    public MatchEvent MatchEvent { get; set; } = null!;
    public EventRevisionAction Action { get; set; }
    public string? OldValuesJson { get; set; }
    public string? NewValuesJson { get; set; }
    [StringLength(500)] public string? Reason { get; set; }
    public string? ChangedByUserId { get; set; }
    public ApplicationUser? ChangedByUser { get; set; }
}

public class MatchLineup : BaseEntity
{
    public int MatchId { get; set; }
    public Match Match { get; set; } = null!;
    public int TeamId { get; set; }
    public Team Team { get; set; } = null!;
    public int PlayerId { get; set; }
    public Player Player { get; set; } = null!;
    public int? ShirtNumber { get; set; }
    public int? PositionId { get; set; }
    public SportPosition? Position { get; set; }
    public bool IsStarter { get; set; }
    public bool IsCaptain { get; set; }
}

public class MatchOfficial : BaseEntity
{
    public int MatchId { get; set; }
    public Match Match { get; set; } = null!;
    public MatchOfficialRole Role { get; set; }
    [Required, StringLength(150)] public string Name { get; set; } = string.Empty;
}

public class MatchReport : BaseEntity
{
    public int MatchId { get; set; }
    public Match Match { get; set; } = null!;
    [StringLength(4000)] public string? Summary { get; set; }
    public int? Attendance { get; set; }
    /// <summary>Best player of the match (feeds "أفضل لاعب" statistics).</summary>
    public int? BestPlayerId { get; set; }
    public Player? BestPlayer { get; set; }
    public string? WrittenByUserId { get; set; }
    public ApplicationUser? WrittenByUser { get; set; }
}
